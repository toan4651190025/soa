CREATE TABLE dangky (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sinh_vien_id BIGINT NOT NULL,
    de_tai_id BIGINT NOT NULL,
    ma_sinh_vien VARCHAR(30),
    ten_sinh_vien VARCHAR(120),
    ma_de_tai VARCHAR(30),
    ten_de_tai VARCHAR(200),
    giang_vien_huong_dan VARCHAR(120),
    trang_thai VARCHAR(30) NOT NULL,
    diem_huong_dan DOUBLE PRECISION,
    diem_phan_bien DOUBLE PRECISION,
    diem_hoi_dong DOUBLE PRECISION,
    CONSTRAINT ck_dangky_status CHECK (trang_thai IN ('DANG_KY', 'DANG_THUC_HIEN', 'DA_HOAN_THANH')),
    CONSTRAINT ck_dangky_diem_huong_dan CHECK (diem_huong_dan IS NULL OR (diem_huong_dan >= 0 AND diem_huong_dan <= 10)),
    CONSTRAINT ck_dangky_diem_phan_bien CHECK (diem_phan_bien IS NULL OR (diem_phan_bien >= 0 AND diem_phan_bien <= 10)),
    CONSTRAINT ck_dangky_diem_hoi_dong CHECK (diem_hoi_dong IS NULL OR (diem_hoi_dong >= 0 AND diem_hoi_dong <= 10)),
    CONSTRAINT uk_dangky_sinhvien_detai UNIQUE (sinh_vien_id, de_tai_id)
);

CREATE INDEX idx_dangky_sinh_vien_id ON dangky (sinh_vien_id);
CREATE INDEX idx_dangky_de_tai_id ON dangky (de_tai_id);
