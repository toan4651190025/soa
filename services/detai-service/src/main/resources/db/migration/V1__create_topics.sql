CREATE TABLE detai (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ma_de_tai VARCHAR(30) NOT NULL UNIQUE,
    ten_de_tai VARCHAR(200) NOT NULL,
    giang_vien_huong_dan VARCHAR(120) NOT NULL,
    chi_tieu INTEGER NOT NULL,
    mo_ta VARCHAR(2000),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_detai_chi_tieu CHECK (chi_tieu >= 1)
);
